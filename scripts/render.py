def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--examples", action="store_true", help="also render rows marked example: true")
    args = ap.parse_args()

    try:
        rows = load_rows()
    except Exception as exc:  # bad YAML or wrong shape: say so, write nothing
        print(f"render: cannot read data/announcements.yaml: {exc}", file=sys.stderr)
        return 1
    bad = [r for r in rows if not isinstance(r, dict) or r.get("area") not in AREAS
           or r.get("status") not in STATUSES]
    if bad:
        print("render: rows with a missing or unknown area/status; run scripts/check.py", file=sys.stderr)
        return 1

    rows = sorted((r for r in rows if args.examples or not r.get("example")), key=sort_key)
    README.write_text(readme(rows, args.examples), encoding="utf-8")
    INDEX.parent.mkdir(parents=True, exist_ok=True)
    INDEX.write_text(index_html(rows, args.examples), encoding="utf-8")
    shown = "including examples" if args.examples else "examples hidden"
    print(f"render: {len(rows)} row(s) ({shown}) -> README.md, docs/index.html")
    return 0


if __name__ == "__main__":
    sys.exit(main())
