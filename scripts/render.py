#!/usr/bin/env python3
"""Render data/announcements.yaml into README.md and docs/index.html.

Usage:
    python scripts/render.py              real rows only (what gets published)
    python scripts/render.py --examples   also render rows marked example: true

The output is deterministic: the same YAML always gives the same files, so a
diff shows only what changed in the data. "Last updated" is the most recent
verified_at across the rendered rows, not the time of the run.
"""

import argparse
import html
import re
import sys

from schema import (AREAS, INDEX, README, STATUSES, TEMPLATES, TITLE, as_text,
                    load_rows, slug)

STATUS_CLASS = {
    "GA": "s-ga",
    "Public preview": "s-pub",
    "Preview": "s-pub",
    "Private preview": "s-priv",
    "Announced": "s-ann",
}


def sort_key(row):
    area = AREAS.index(row["area"]) if row.get("area") in AREAS else len(AREAS)
    status = STATUSES.index(row["status"]) if row.get("status") in STATUSES else len(STATUSES)
    return (area, status, as_text(row.get("title")).lower())


def last_updated(rows):
    dates = sorted(as_text(r.get("verified_at")) for r in rows if r.get("verified_at"))
    return dates[-1] if dates else ""


def read_template(name):
    return (TEMPLATES / name).read_text(encoding="utf-8").strip()


# ---------- README.md ----------

def md_cell(value):
    text = re.sub(r"\s+", " ", as_text(value))
    return text.replace("|", "\\|")


def readme(rows, examples):
    out = [
        f"<!-- Generated by scripts/render.py from data/announcements.yaml. "
        f"Edit the YAML, not this file. examples: {'yes' if examples else 'no'} -->",
        "",
        f"# {TITLE}",
        "",
        read_template("intro.md"),
        "",
    ]
    if rows:
        n = len(rows)
        out.append(f"**Last updated:** {last_updated(rows)} (most recent verification across "
                   f"{n} announcement{'s' if n != 1 else ''}). A filterable version of this "
                   f"list is in `docs/index.html`.")
    else:
        out.append("**Last updated:** no announcements yet. Rows are added once Microsoft "
                   "has published them.")
    out.append("")

    header = ("| Announcement | Status | Available | What changes | Do Monday | Learn | Sessions | Verified |\n"
              "|---|---|---|---|---|---|---|---|")
    for area in AREAS:
        group = [r for r in rows if r["area"] == area]
        if not group:
            continue
        out += [f"## {area}", "", header]
        for r in group:
            title = md_cell(r["title"])
            if r.get("example"):
                title += " (example)"
            learn = f"[Learn]({r['learn_url']})" if as_text(r.get("learn_url")) else ""
            sessions = ", ".join(md_cell(s) for s in (r.get("sessions") or []))
            out.append(
                f"| [{title}]({as_text(r['source_url'])}) | {md_cell(r['status'])} "
                f"| {md_cell(r.get('available'))} | {md_cell(r['what_changes'])} "
                f"| {md_cell(r['do_monday'])} | {learn} | {sessions} "
                f"| {md_cell(r['verified_at'])} |"
            )
        out.append("")

    out.append(read_template("footer.md"))
    return "\n".join(out) + "\n"


# ---------- docs/index.html ----------

def inline_md(text):
    """The small subset of Markdown the intro uses: bold, code, links."""
    text = html.escape(text, quote=True)
    text = re.sub(r"\*\*(.+?)\*\*", r"<strong>\1</strong>", text)
    text = re.sub(r"`(.+?)`", r"<code>\1</code>", text)
    text = re.sub(r"\[(.+?)\]\((https?://[^)\s]+)\)", r'<a href="\2">\1</a>', text)
    return text


def intro_html():
    """First paragraph in full; the rest folds away so the list starts on screen."""
    paras = [p.strip() for p in re.split(r"\n\s*\n", read_template("intro.md")) if p.strip()]
    html_paras = [f"<p>{inline_md(' '.join(p.split()))}</p>" for p in paras]
    if len(html_paras) == 1:
        return html_paras[0]
    return (html_paras[0] + '\n<details class="about"><summary>What it covers and how status is verified</summary>\n'
            + "\n".join(html_paras[1:]) + "\n</details>")


def e(value):
    return html.escape(as_text(value), quote=True)


def card(r):
    status = r["status"]
    meta = [f'<span class="status {STATUS_CLASS.get(status, "s-ann")}">{e(status)}</span>']
    if as_text(r.get("available")):
        meta.append(f"<span>Available {e(r['available'])}</span>")
    if r.get("example"):
        meta.append('<span class="ex">Example</span>')
    links = []
    if as_text(r.get("learn_url")):
        links.append(f'<a href="{e(r["learn_url"])}">Learn</a>')
    sessions = r.get("sessions") or []
    if sessions:
        links.append("Sessions: " + ", ".join(e(s) for s in sessions))
    links.append(f"Verified {e(r['verified_at'])}")
    return f"""<article class="row" id="{e(r['id'])}" data-area="{slug(r['area'])}" data-status="{slug(status)}">
<p class="meta">{''.join(meta)}</p>
<h3><a href="{e(r['source_url'])}">{e(r['title'])}</a></h3>
<dl>
<dt>What changes</dt><dd>{e(r['what_changes'])}</dd>
<dt>Do Monday</dt><dd>{e(r['do_monday'])}</dd>
</dl>
<p class="links">{' <span aria-hidden="true">&middot;</span> '.join(links)}</p>
</article>"""


